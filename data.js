const NON_VEG = new Set(['tuna', 'sardines', 'sausage', 'frankfurters', 'ham', 'chicken', 'dumplings'])
export const isVegetarian = (recipe) => !recipe.ingredients.some((i) => NON_VEG.has(i))

export const FILTER_TESTS = {
  noStove: (r) => r.noStove,
  quick: (r) => r.time <= 5,
  simple: (r) => r.actions <= 3,
  fewDishes: (r) => r.fewDishes,
  cold: (r) => r.cold,
  noChop: (r) => r.noChop,
  batch: (r) => r.batch,
  veg: isVegetarian,
}

// ---------- Рецепты ----------
// energy: 1 — почти без усилий, 2 — немного, 3 — можно поготовить
// ingredients — обязательные, optional — «можно добавить»
const timeLabel = (t) => (t <= 5 ? `${t} мин` : `${Math.round(t * 0.7)}–${t} мин`)

const R = (id, title, emoji, time, actions, energy, flags, ingredients, optional, desc, steps, tip = '', subs) => ({
  id,
  title,
  emoji,
  time,
  timeLabel: timeLabel(time),
  actions,
  energy,
  cold: flags.includes('C'),
  noStove: flags.includes('N') || flags.includes('C'),
  fewDishes: flags.includes('D'),
  noChop: flags.includes('K'),
  familiar: flags.includes('F'),
  batch: flags.includes('B'),
  ingredients,
  optional,
  desc,
  steps,
  tip,
  subs,
})

